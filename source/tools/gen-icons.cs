// Writes ExifGlass.UI's icon geometries (Themes/Icons.axaml, Controls/IconId.g.cs) from __assets/icons (O16, plan 5.8). Run from source/tools: dotnet run gen-icons.cs [-- --check]
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.RegularExpressions;

var check = args.Contains("--check");
var sourceDir = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(ThisFile())!, ".."));
var iconsDir = Path.Combine(sourceDir, "__assets", "icons");
var axamlPath = Path.Combine(sourceDir, "ExifGlass.UI", "Themes", "Icons.axaml");
var codePath = Path.Combine(sourceDir, "ExifGlass.UI", "Controls", "IconId.g.cs");

var axaml = new StringBuilder();
var catalog = new StringBuilder();
var ids = new List<string>();
var errors = new List<string>();

axaml.AppendLine("""
    <ResourceDictionary xmlns="https://github.com/avaloniaui"
                        xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">

      <!--  generated by source/tools/gen-icons.cs from source/__assets/icons; do not edit  -->

    """);

// glass: drawn for ExifGlass, round-capped strokes in a 20 box; fill="currentColor" also fills, class="cut" is knocked out of the fill
foreach (var file in Directory.GetFiles(Path.Combine(iconsDir, "glass"), "*.svg").OrderBy(f => f, StringComparer.Ordinal))
{
    Add(file, isBrand: false);
}

// brand: official marks drawn as they are, filled (plan 5.8)
foreach (var file in Directory.GetFiles(Path.Combine(iconsDir, "brand"), "*.svg").OrderBy(f => f, StringComparer.Ordinal))
{
    Add(file, isBrand: true);
}

if (errors.Count > 0)
{
    foreach (var e in errors) Console.Error.WriteLine(e);
    return 2;
}

axaml.AppendLine();
axaml.AppendLine("</ResourceDictionary>");

var code = $$"""
    {{Header()}}
    // <auto-generated/> by source/tools/gen-icons.cs; do not edit
    namespace ExifGlass.UI.Controls;

    /// <summary>
    /// The app's icons (O16): one per SVG source in source/__assets/icons.
    /// </summary>
    public enum IconId
    {
    {{string.Join("\n", ids.Select(i => $"    {i},"))}}
    }


    internal static partial class IconCatalog
    {
        /// <summary>
        /// Gets how an icon is drawn: its box, its stroke width and which geometries it has.
        /// </summary>
        public static IconSpec Get(IconId id) => id switch
        {
    {{catalog.ToString().TrimEnd()}}
            _ => throw new ArgumentOutOfRangeException(nameof(id)),
        };
    }

    """;

var outputs = new (string Path, string Content)[] { (axamlPath, axaml.ToString().Replace("\r\n", "\n")), (codePath, code.Replace("\r\n", "\n")) };
var stale = 0;
foreach (var (path, content) in outputs)
{
    var current = File.Exists(path) ? File.ReadAllText(path).Replace("\r\n", "\n") : null;
    var relative = Path.GetRelativePath(sourceDir, path);
    if (current == content)
    {
        Console.WriteLine($"  up to date  {relative}");
        continue;
    }

    stale++;
    if (check)
    {
        Console.WriteLine($"  STALE       {relative}");
        continue;
    }

    File.WriteAllText(path, content);
    Console.WriteLine($"  written     {relative}");
}

Console.WriteLine($"  {ids.Count} icons");
return check && stale > 0 ? 1 : 0;


void Add(string file, bool isBrand)
{
    var name = Path.GetFileNameWithoutExtension(file);
    var id = (isBrand ? "Brand" : "") + ToPascal(name);
    var svg = File.ReadAllText(file);
    var root = Regex.Match(svg, @"<svg\b([^>]*)>").Groups[1].Value;
    var box = Attr(root, "viewBox")!.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(Num).ToArray();
    var width = isBrand ? 0 : Num(Attr(root, "stroke-width") ?? "1.5");
    var stroke = new List<string>();
    var fill = new List<string>();
    var cut = new List<string>();

    foreach (Match tag in Regex.Matches(svg, @"<(/?)([a-zA-Z]+)\b([^>]*?)(/?)>"))
    {
        var element = tag.Groups[2].Value;
        if (element is "svg" || tag.Groups[1].Value == "/") continue;

        if (element is not ("path" or "circle" or "rect")) errors.Add($"{name}: <{element}> isn't allowed");

        var attrs = tag.Groups[3].Value;
        foreach (Match a in Regex.Matches(attrs, @"([\w:-]+)\s*="))
        {
            var allowed = element switch
            {
                "path" => new[] { "d", "fill", "stroke", "class" },
                "circle" => ["cx", "cy", "r", "fill", "stroke", "class"],
                "rect" => ["x", "y", "width", "height", "rx", "fill", "stroke", "class"],
                _ => [],
            };
            if (!allowed.Contains(a.Groups[1].Value)) errors.Add($"{name}: attribute {a.Groups[1].Value} on <{element}> isn't allowed");
        }

        var d = element switch
        {
            "circle" => CirclePath(Num(Attr(attrs, "cx")!), Num(Attr(attrs, "cy")!), Num(Attr(attrs, "r")!)),
            "rect" => RectPath(Num(Attr(attrs, "x")!), Num(Attr(attrs, "y")!), Num(Attr(attrs, "width")!), Num(Attr(attrs, "height")!), Num(Attr(attrs, "rx") ?? "0")),
            _ => NormalizePath(name, Attr(attrs, "d")!),
        };

        if (isBrand) fill.Add(d);
        else if (Attr(attrs, "class") == "cut") cut.Add(d);
        else if (Attr(attrs, "fill") == "currentColor")
        {
            fill.Add(d);
            if (Attr(attrs, "stroke") != "none") stroke.Add(d);
        }
        else stroke.Add(d);
    }

    if (stroke.Count > 0) axaml.AppendLine($"""  <StreamGeometry x:Key="Icon.{id}.Stroke">{string.Join(" ", stroke)}</StreamGeometry>""");
    if (fill.Count > 0) axaml.AppendLine($"""  <StreamGeometry x:Key="Icon.{id}.Fill">{string.Join(" ", fill)}</StreamGeometry>""");
    if (cut.Count > 0) axaml.AppendLine($"""  <StreamGeometry x:Key="Icon.{id}.Cut">{string.Join(" ", cut)}</StreamGeometry>""");

    ids.Add(id);
    catalog.AppendLine($"""        IconId.{id} => new({F(box[0])}, {F(box[1])}, {F(box[2])}, {F(width)}, {B(stroke.Count > 0)}, {B(fill.Count > 0)}, {B(cut.Count > 0)}),""");
}


static string ThisFile([CallerFilePath] string path = "") => path;

static string Header() => File.ReadAllText(ThisFile()).Split("*/")[0] + "*/";

static string ToPascal(string name) => string.Concat(name.Split('_', '-').Select(p => char.ToUpperInvariant(p[0]) + p[1..]));

static string? Attr(string attrs, string name) => Regex.Match(attrs, $"(?<![\\w-]){name}=\"([^\"]*)\"") is { Success: true } m ? m.Groups[1].Value : null;

static double Num(string text) => double.Parse(text, CultureInfo.InvariantCulture);

static string F(double v) => v.ToString("0.###", CultureInfo.InvariantCulture);

static string B(bool v) => v ? "true" : "false";

static string CirclePath(double cx, double cy, double r) => $"M {F(cx - r)} {F(cy)} A {F(r)} {F(r)} 0 1 0 {F(cx + r)} {F(cy)} A {F(r)} {F(r)} 0 1 0 {F(cx - r)} {F(cy)} Z";

static string RectPath(double x, double y, double w, double h, double r) => r <= 0
    ? $"M {F(x)} {F(y)} H {F(x + w)} V {F(y + h)} H {F(x)} Z"
    : $"M {F(x + r)} {F(y)} H {F(x + w - r)} A {F(r)} {F(r)} 0 0 1 {F(x + w)} {F(y + r)} V {F(y + h - r)} A {F(r)} {F(r)} 0 0 1 {F(x + w - r)} {F(y + h)} H {F(x + r)} A {F(r)} {F(r)} 0 0 1 {F(x)} {F(y + h - r)} V {F(y + r)} A {F(r)} {F(r)} 0 0 1 {F(x + r)} {F(y)} Z";


// splits SVG's compact number syntax ("9.41.58", "-1.27q-1") into tokens Avalonia's parser reads; arc flags must be single 0 or 1 tokens
string NormalizePath(string name, string d)
{
    var tokens = Regex.Matches(d, @"[A-Za-z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?").Select(t => t.Value).ToList();
    var command = ' ';
    var argument = 0;
    foreach (var t in tokens)
    {
        if (char.IsLetter(t[0]))
        {
            command = t[0];
            argument = 0;
            continue;
        }

        if (command is 'a' or 'A')
        {
            var slot = argument % 7;
            if (slot is 3 or 4 && t is not ("0" or "1")) errors.Add($"{name}: arc flag '{t}' must be 0 or 1 (write flags apart)");
        }

        argument++;
    }

    // a path's first m is absolute in SVG, but merged after another path it would be relative to that one's end; the pairs after it stay relative lines
    if (tokens.Count > 2 && tokens[0] == "m")
    {
        tokens[0] = "M";
        if (tokens.Count > 3 && !char.IsLetter(tokens[3][0])) tokens.Insert(3, "l");
    }

    return string.Join(" ", tokens);
}
