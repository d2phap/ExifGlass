    public static void PrintPaletteReport()
    {
        Console.WriteLine();
        Console.WriteLine("  Group palette: contrast against Bg.Panel (light / dark)");
        foreach (var (name, light, dark, baseHex) in PaletteEntries())
        {
            var mark = light != baseHex || dark != baseHex ? " tuned" : "";
            Console.WriteLine(Invariant($"  {name,-12} {light} {Contrast(light, PANEL_LIGHT):0.00}  {dark} {Contrast(dark, PANEL_DARK):0.00}  (base {baseHex}){mark}"));
        }
    }


    static string TokensAxaml()
    {
        var light = new StringBuilder();
        var dark = new StringBuilder();
        const string pad = "      ";

        foreach (var c in Colors)
        {
            ColorPair(light, pad, c.Key, c.Light);
            ColorPair(dark, pad, c.Key, c.Dark);
        }

        foreach (var family in Families.Where(f => f.Light != f.Dark))
        {
            light.AppendLine($"{pad}<!--  {family.Name} alphas: {family.Use}  -->");
            dark.AppendLine($"{pad}<!--  {family.Name} alphas: {family.Use}  -->");
            foreach (var p in family.Percents)
            {
                ColorPair(light, pad, AlphaKey(family.Name, p), WithAlpha(family.Light, p));
                ColorPair(dark, pad, AlphaKey(family.Name, p), WithAlpha(family.Dark, p));
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("""
            <ResourceDictionary xmlns="https://github.com/avaloniaui"
                                xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">

              <!--  generated by source/tools/gen-tokens.cs from the design spec (DS 1.2-1.5, 3, 5); do not edit  -->

              <ResourceDictionary.ThemeDictionaries>
                <ResourceDictionary x:Key="Light">
            """);
        sb.Append(light);
        sb.AppendLine("""
                </ResourceDictionary>

                <ResourceDictionary x:Key="Dark">
            """);
        sb.Append(dark);
        sb.AppendLine("""
                </ResourceDictionary>
              </ResourceDictionary.ThemeDictionaries>
            """);

        const string root = "  ";
        sb.AppendLine();
        sb.AppendLine($"{root}<!--  The same in both themes  -->");
        foreach (var (key, value, _) in FixedColors) ColorPair(sb, root, key, value);

        foreach (var family in Families.Where(f => f.Light == f.Dark))
        {
            sb.AppendLine();
            sb.AppendLine($"{root}<!--  {family.Name} alphas: {family.Use}  -->");
            foreach (var p in family.Percents) ColorPair(sb, root, AlphaKey(family.Name, p), WithAlpha(family.Light, p));
        }

        sb.AppendLine();
        sb.AppendLine($"{root}<!--  Corner radius: min(16, round(height x 0.45)) for controls, DS 3.2 for containers  -->");
        foreach (var (key, radius, _) in Radii) sb.AppendLine($"{root}<CornerRadius x:Key=\"{key}\">{Num(radius)}</CornerRadius>");

        sb.AppendLine();
        sb.AppendLine($"{root}<!--  Spacing (DS 1.4)  -->");
        foreach (var s in Spacing) sb.AppendLine($"{root}<x:Double x:Key=\"Space{Num(s)}\">{Num(s)}</x:Double>");

        sb.AppendLine();
        sb.AppendLine($"{root}<!--  Sizes (DS 6)  -->");
        foreach (var (key, value, _) in Sizes) sb.AppendLine($"{root}<x:Double x:Key=\"{key}\">{Num(value)}</x:Double>");

        sb.AppendLine();
        sb.AppendLine($"{root}<!--  Elevation (DS 1.5): CSS blur converted to Avalonia's  -->");
        foreach (var (key, css, _) in Shadows) sb.AppendLine($"{root}<BoxShadows x:Key=\"{key}\">{Shadow(css)}</BoxShadows>");

        sb.AppendLine();
        sb.AppendLine($"{root}<!--  Font sizes (DS 1.1); mono +1 off Windows cancels the -1 pt coercion (S3)  -->");
        foreach (var (key, size, mono) in FontSizes)
        {
            sb.AppendLine(mono
                ? $"{root}<OnPlatform x:Key=\"{key}\" x:TypeArguments=\"x:Double\" Default=\"{Num(size + 1)}\" Windows=\"{Num(size)}\" />"
                : $"{root}<x:Double x:Key=\"{key}\">{Num(size)}</x:Double>");
        }

        sb.AppendLine();
        sb.AppendLine($"{root}<!--  Fonts: one family name on Windows (a fallback list switches non-400 weights to static Segoe UI); AppFonts picks the system mono  -->");
