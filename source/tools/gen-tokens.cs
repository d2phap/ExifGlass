    #region Palette

    static IEnumerable<(string Name, string Light, string Dark, string Base)> PaletteEntries()
    {
        foreach (var g in Groups)
        {
            yield return (g.Group, Tune(g.Base, PANEL_LIGHT, darken: true), Tune(g.Base, PANEL_DARK, darken: false), g.Base);
        }

        for (var i = 0; i < RING_SIZE; i++)
        {
            var hue = RING_FIRST_HUE + (RING_LAST_HUE - RING_FIRST_HUE) * i / (RING_SIZE - 1);
            var hex = FromOklch(RING_L, RING_C, hue);
            yield return (Invariant($"ring{i}"), Tune(hex, PANEL_LIGHT, darken: true), Tune(hex, PANEL_DARK, darken: false), hex);
        }
    }


    // moves OKLab lightness until the colour keeps 3:1 against the panel; hue and chroma stay
    static string Tune(string hex, string panel, bool darken)
    {
        if (Contrast(hex, panel) >= MIN_CONTRAST) return hex;

        var (l, c, h) = ToOklch(hex);
        for (var step = 0; step < 400; step++)
        {
            l += darken ? -0.0025 : 0.0025;
            var candidate = FromOklch(l, c, h);
            if (Contrast(candidate, panel) >= MIN_CONTRAST) return candidate;
        }

        return hex;
    }


    static double Contrast(string a, string b)
    {
        var (la, lb) = (Luminance(a), Luminance(b));
        return (Math.Max(la, lb) + 0.05) / (Math.Min(la, lb) + 0.05);
    }


    static double Luminance(string hex)
    {
        var (r, g, b) = Rgb(hex);
        static double Lin(double v) => v <= 0.04045 ? v / 12.92 : Math.Pow((v + 0.055) / 1.055, 2.4);
        return 0.2126 * Lin(r) + 0.7152 * Lin(g) + 0.0722 * Lin(b);
    }


    static (double L, double C, double H) ToOklch(string hex)
    {
        var (r, g, b) = Rgb(hex);
        static double Lin(double v) => v <= 0.04045 ? v / 12.92 : Math.Pow((v + 0.055) / 1.055, 2.4);
        (r, g, b) = (Lin(r), Lin(g), Lin(b));

        var l = Math.Cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
        var m = Math.Cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
        var s = Math.Cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);

        var lightness = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s;
        var a = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s;
        var bb = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s;
        return (lightness, Math.Sqrt(a * a + bb * bb), Math.Atan2(bb, a) * 180 / Math.PI);
    }


    // out-of-gamut colours lose chroma until they fit
    static string FromOklch(double lightness, double chroma, double hue)
    {
        for (var c = chroma; c >= 0; c -= 0.002)
        {
            var a = c * Math.Cos(hue * Math.PI / 180);
            var b = c * Math.Sin(hue * Math.PI / 180);

            var l = Math.Pow(lightness + 0.3963377774 * a + 0.2158037573 * b, 3);
            var m = Math.Pow(lightness - 0.1055613458 * a - 0.0638541728 * b, 3);
            var s = Math.Pow(lightness - 0.0894841775 * a - 1.2914855480 * b, 3);

            var r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
            var g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
            var bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s;

            if (r is < -1e-4 or > 1.0001 || g is < -1e-4 or > 1.0001 || bl is < -1e-4 or > 1.0001) continue;

            static int Gamma(double v)
            {
                v = Math.Clamp(v, 0, 1);
                v = v <= 0.0031308 ? 12.92 * v : 1.055 * Math.Pow(v, 1 / 2.4) - 0.055;
                return (int)Math.Round(v * 255);
            }

            return $"#{Gamma(r):X2}{Gamma(g):X2}{Gamma(bl):X2}";
        }

        return "#808080";
    }


    static (double R, double G, double B) Rgb(string hex)
    {
        var h = hex.TrimStart('#');
        if (h.Length == 8) h = h[2..];
        return (Convert.ToInt32(h[0..2], 16) / 255.0, Convert.ToInt32(h[2..4], 16) / 255.0, Convert.ToInt32(h[4..6], 16) / 255.0);
    }

