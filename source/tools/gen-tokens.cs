    #region Helpers

    static void ColorPair(StringBuilder sb, string pad, string key, string hex)
    {
        sb.AppendLine($"{pad}<Color x:Key=\"{key}Color\">{hex}</Color>");
        sb.AppendLine($"{pad}<SolidColorBrush x:Key=\"{key}Brush\" Color=\"{hex}\" />");
    }


    // 6% is A06, 3.5% is A035
    static string AlphaKey(string family, double percent) => percent == Math.Floor(percent)
        ? Invariant($"{family}A{percent:00}")
        : Invariant($"{family}A{percent * 10:000}");


    static string WithAlpha(string hex, double percent)
    {
        var alpha = (int)Math.Round(percent / 100 * 255);
        return $"#{alpha:X2}{hex.TrimStart('#')}";
    }


    // "0 18 50 -12 rgba(0,0,0,.35)" to Avalonia's "0 18 84.87 -12 #59000000"
    static string Shadow(string css)
    {
        var parts = css.Split(' ', 5);
        var rgba = parts[4].Trim()["rgba(".Length..^1].Split(',');
        var (r, g, b) = (int.Parse(rgba[0], CultureInfo.InvariantCulture), int.Parse(rgba[1], CultureInfo.InvariantCulture), int.Parse(rgba[2], CultureInfo.InvariantCulture));
        var a = (int)Math.Round(double.Parse(rgba[3], CultureInfo.InvariantCulture) * 255);
        var blur = AvaloniaBlur(double.Parse(parts[2], CultureInfo.InvariantCulture));
        return $"{parts[0]} {parts[1]} {Num(blur)} {parts[3]} #{a:X2}{r:X2}{g:X2}{b:X2}";
    }


    // Chrome's blur is 2 sigma; Avalonia's sigma is 0.288675 * blur + 0.5 (FewerPhotos F14)
    static double AvaloniaBlur(double cssBlur) => cssBlur <= 1 ? cssBlur : Math.Round((cssBlur / 2 - 0.5) / 0.288675, 2);


    static string WeightName(int weight) => weight switch
    {
        400 => "Normal",
        500 => "Medium",
        600 => "SemiBold",
        _ => throw new ArgumentOutOfRangeException(nameof(weight), "DS: 400, 500 and 600 only"),
    };


    static string Snake(string pascal)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < pascal.Length; i++)
        {
            var ch = pascal[i];
            // digits stay with the word before them: Accent2A10Brush is ACCENT2_A10_BRUSH
            if (i > 0 && char.IsUpper(ch) && (char.IsLower(pascal[i - 1]) || char.IsDigit(pascal[i - 1]))) sb.Append('_');
            sb.Append(char.ToUpperInvariant(ch));
        }

        return sb.ToString();
    }


    static string Pascal(string kebab) => string.Concat(kebab.Split('-').Select(p => char.ToUpperInvariant(p[0]) + p[1..]));


    static string Num(double v) => v.ToString("0.###", CultureInfo.InvariantCulture);


    static string Bool(bool v) => v ? "true" : "false";


    static string Invariant(FormattableString s) => s.ToString(CultureInfo.InvariantCulture);


    static string Lf(string s) => s.Replace("\r\n", "\n");

